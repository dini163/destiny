"""洛书九宫方阵、八个平面（箭矢）与缺数释义（spec §5.4）。

**摆法是真洛书，不是设计稿的升序摆法。** 设计稿把九宫画成 `3 6 9 / 2 5 8 / 1 4 7`，
行和是 18/15/12，不具幻方性质；那样摆的话下面八个"平面/箭矢"就只是三堆互不相干的
数字。真正的洛书幻方是 `4 9 2 / 3 5 7 / 8 1 6`，三行、三列、两对角线各自都等于 15，
而八个平面**正好就是这八条线**。故本模块把方阵写死，并由
`tests/content/test_numerology_corpora.py` 断言幻方性质与"八组 cells == 八条线"
（spec 决策 12）—— 这条测试存在的唯一目的，就是防止有人日后按设计稿改回升序摆法，
静默毁掉全部箭矢。

传统归属必须说清：洛书九宫与八平面属**印度数理（Vedic/Lo Shu grid）**传统，不是
毕达哥拉斯体系的一部分。本仓把它与姓名天赋九宫分开呈现、独立署名（spec §11 残余
风险 3），输入也不同：这一张数的是**生日的字面数字**，不是姓名字母。
"""

from __future__ import annotations

from dataclasses import dataclass

#: 书级出处：自认是通行整理稿，且自认不属毕达哥拉斯体系。
LOSHU_SOURCE = "洛书九宫与八平面箭矢（印度数理通行整理稿，非古籍、非毕达哥拉斯体系）"

#: 洛书幻方。每格数字只出现一次，八条线各自和为 15。
LOSHU_SQUARE: tuple[tuple[int, int, int], ...] = (
    (4, 9, 2),
    (3, 5, 7),
    (8, 1, 6),
)


@dataclass(frozen=True)
class Plane:
    key: str
    name_zh: str
    name_en: str
    #: 构成数字，严格是洛书的一条线（行/列/对角线），顺序照来源印出的顺序。
    cells: tuple[int, int, int]
    present_text: str
    missing_text: str
    source: str


def _plane(
    key: str,
    name_zh: str,
    name_en: str,
    cells: tuple[int, int, int],
    present_text: str,
    missing_text: str,
) -> Plane:
    return Plane(
        key=key,
        name_zh=name_zh,
        name_en=name_en,
        cells=cells,
        present_text=present_text,
        missing_text=missing_text,
        source=f"{LOSHU_SOURCE}·{name_en}",
    )


