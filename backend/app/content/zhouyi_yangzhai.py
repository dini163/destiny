def get_yangzhai_hexagram_meaning(hexagram_name: str) -> dict[str, Any] | None:
    """根据卦名返回其在阳宅九宫与六十四卦中的化命取象。"""
    pair = HEXAGRAM_COMPONENTS.get(hexagram_name)
    if not pair:
        return None
    upper, lower = pair
    u_info = TRIGRAM_ROLE_DIR.get(upper, {})
    l_info = TRIGRAM_ROLE_DIR.get(lower, {})

    is_name_position_equal = upper == lower

    person_role = u_info.get("role", "")
    position_dir = l_info.get("direction", "")

    if is_name_position_equal:
        summary = f"【名位相等】{person_role}居{position_dir}正位，各归其位，天地定序，吉顺安详。"
    else:
        summary = f"【化命成卦】家庭身份为「{person_role}」居住在「{position_dir}」位置，化出此《{hexagram_name}》卦。"

    return {
        "hexagram": hexagram_name,
        "upper_trigram": upper,
        "lower_trigram": lower,
        "person_role": person_role,
        "position_direction": position_dir,
        "is_name_position_equal": is_name_position_equal,
        "summary": summary,
        "principle": "阳宅地脉堪舆法则：名位相等为吉；若名位不副，借方位之气化出卦象，可作居所调和与性格修养之参考。",
    }

